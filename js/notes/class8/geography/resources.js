/* ---------- Answer button helpers ---------- */

function cqEscapeHTML(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

/*
 * Use this markup for every question:
 *
 * <article class="cq-question-card">
 *   <h3>Question...</h3>
 *   <button class="cq-answer-btn" type="button"
 *           onclick="cqToggleAnswer(this)">💡 Show Answer</button>
 *   <div class="cq-answer" hidden>Answer...</div>
 * </article>
 */
window.cqToggleAnswer = function(button) {
  const answer = button.nextElementSibling;
  if (!answer) return;

  const isHidden = answer.hasAttribute("hidden");
  if (isHidden) {
    answer.removeAttribute("hidden");
    button.textContent = "🙈 Hide Answer";
    button.setAttribute("aria-expanded", "true");
  } else {
    answer.setAttribute("hidden", "");
    button.textContent = "💡 Show Answer";
    button.setAttribute("aria-expanded", "false");
  }
};


/* ---------- Optional renderer for question sections ---------- */

function cqQuestionCard(item, index, accentClass) {
  return `
    <article class="cq-question-card ${accentClass || ""}">
      <div class="cq-question-number">Q${index + 1}</div>
      <div class="cq-question">${cqEscapeHTML(item.question)}</div>
      <button class="cq-answer-btn" type="button"
              aria-expanded="false"
              onclick="cqToggleAnswer(this)">💡 Show Answer</button>
      <div class="cq-answer" hidden>
        ${cqEscapeHTML(item.answer)}
      </div>
    </article>
  `;
}

window.renderResourcesPracticeQuestions = function(container) {
  if (!container) return;

  const groups = [
    ["Very Short Answer", chapterData.practiceQuestions.veryShortAnswer, "blue"],
    ["Short Answer", chapterData.practiceQuestions.shortAnswer, "green"],
    ["Long Answer", chapterData.practiceQuestions.longAnswer, "purple"],
    ["Challenge Zone", chapterData.practiceQuestions.challengeZone, "orange"]
  ];

  container.innerHTML = `
    <section class="cq-section">
      <h2>Practice Questions</h2>
      ${groups.map(([title, items, cls]) => `
        <div class="cq-practice-group ${cls}">
          <h3>✏️ ${title}</h3>
          ${items.map((item, i) => cqQuestionCard(item, i, cls)).join("")}
        </div>
      `).join("")}
    </section>
  `;
};

